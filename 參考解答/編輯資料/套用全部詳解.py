def splittext(t):
 t=re.sub(r'與\s*112\s*年第一題相同：','',t)
 t=re.sub(r'(?<!\d)([1-9]|10)\s+(?=[A-Za-z])',r'\n\1. ',t) if 'Petal' in t else t
 t=re.sub(r'(?<!\d)(\([1-9]\)|（[1-9]）|[①②③④⑤⑥⑦⑧⑨⑩])',r'\n\1',t)
 t=t.replace('；','；\n')
 lines=[]
 for block in t.splitlines():
  block=block.strip()
  if not block:continue
  if len(block)>190:
   ss=re.split(r'(?<=。)',block);buf=''
   for s in ss:
    if len(buf)+len(s)>160 and buf:lines.append(buf);buf=''
    buf+=s
   if buf:lines.append(buf)
  else:lines.append(block)
 return lines

